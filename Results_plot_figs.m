% each UCB .mat file stores its data under the same variable name
% (P_vari_mc_10_ucb / Tracking_error_mc_10_ucb), so load into a struct
% and rename per beta instead of loading directly, to avoid each load
% overwriting the previous beta's data.
% S = load('P_vari_mc_10_ucb_beta01.mat'); P_vari_mc_10_ucb_beta01 = S.P_vari_mc_10_ucb;
% S = load('Tracking_error_mc_10_ucb_beta01.mat'); Tracking_error_mc_10_ucb_beta01 = S.Tracking_error_mc_10_ucb;

S = load('P_vari_mc_10_ucb.mat'); P_vari_mc_10_ucb = S.P_vari_mc_10_ucb;
S = load('Tracking_error_mc_10_ucb.mat'); Tracking_error_mc_10_ucb = S.Tracking_error_mc_10_ucb;

% P_vari_mc_10_ucb.mat and Tracking_error_mc_10_ucb.mat are written by two
% separate save() calls at the end of the UCB script; if a run is stopped
% between them (or only one of the pair gets refreshed by a later partial
% run), the files end up from different runs with different iteration
% counts. Ts_ucb below is built from one of them and then reused as the
% plot() x-vector for both, so a length mismatch here throws "Specify the
% coordinates as vectors...of the same size" in figure(7). Truncate to the
% common length and warn, instead of erroring, so a stale pair is visible
% rather than silently plotted (or crashing) as if it were one run.
if length(P_vari_mc_10_ucb) ~= length(Tracking_error_mc_10_ucb)
    warning('plot_figs:mismatchedUcbRunLength', ...
        ['P_vari_mc_10_ucb.mat (%d pts) and Tracking_error_mc_10_ucb.mat ' ...
         '(%d pts) have different lengths -- they appear to be from ' ...
         'different UCB runs. Truncating both to %d points for plotting; ' ...
         're-run UCB_lego_s1_ros2_urscript_multi_run.m to completion to ' ...
         'regenerate a matched pair.'], ...
        length(P_vari_mc_10_ucb), length(Tracking_error_mc_10_ucb), ...
        min(length(P_vari_mc_10_ucb), length(Tracking_error_mc_10_ucb)));
    nUcb = min(length(P_vari_mc_10_ucb), length(Tracking_error_mc_10_ucb));
    P_vari_mc_10_ucb = P_vari_mc_10_ucb(1:nUcb);
    Tracking_error_mc_10_ucb = Tracking_error_mc_10_ucb(1:nUcb);
end

