%% Plot Function
close all
clear
clc

%%
set(groot, 'defaulttextinterpreter','latex');
set(groot, 'defaultAxesTickLabelInterpreter','latex');
set(groot, 'defaultLegendInterpreter','latex');
set(0, 'defaultFigureUnits', 'centimeters', 'defaultFigurePosition', [0 0 16 9]);

%% Load DCEE, MPC and Entropy results
filenames = {
           'Tracking_error_mc_10_dcee.mat', ...
           'P_vari_mc_10_dcee.mat', ...
           'Tracking_error_mc_10_mpc.mat', ...
           'P_vari_mc_10_mpc.mat', ...
           'Tracking_error_mc_10_entropy.mat', ...
           'P_vari_mc_10_entropy.mat'
          };

for kk = 1:numel(filenames)
    load(filenames{kk})
end

%% Load UCB results
S = load('P_vari_mc_10_ucb.mat'); P_vari_mc_10_ucb = S.P_vari_mc_10_ucb;
S = load('Tracking_error_mc_10_ucb.mat'); Tracking_error_mc_10_ucb = S.Tracking_error_mc_10_ucb;

% The two UCB files may come from different runs; truncate to a common length
if length(P_vari_mc_10_ucb) ~= length(Tracking_error_mc_10_ucb)
    warning('plot_figs:mismatchedUcbRunLength', ...
        ['P_vari_mc_10_ucb.mat (%d pts) and Tracking_error_mc_10_ucb.mat ' ...
         '(%d pts) have different lengths -- they appear to be from ' ...
         'different UCB runs. Truncating both to %d points for plotting; ' ...
         're-run UCB_lego_s1_ros2_urscript_multi_run.m to completion to ' ...
         'regenerate a matched pair.'], ...
        length(P_vari_mc_10_ucb), length(Tracking_error_mc_10_ucb), ...
        min(length(P_vari_mc_10_ucb), length(Tracking_error_mc_10_ucb)));
    nUcb = min(length(P_vari_mc_10_ucb), length(Tracking_error_mc_10_ucb));
    P_vari_mc_10_ucb = P_vari_mc_10_ucb(1:nUcb);
    Tracking_error_mc_10_ucb = Tracking_error_mc_10_ucb(1:nUcb);
end

%% Time steps
Ts_dcee    = 1:1:length(P_vari_mc_10_dcee);
Ts_mpc     = 1:1:length(P_vari_mc_10_mpc);
Ts_entropy = 1:1:length(P_vari_mc_10_entropy);
Ts_ucb     = 1:1:length(P_vari_mc_10_ucb);

%% Distance: DCEE vs MPC vs Entropy
figure(4)
plot(Ts_dcee, Tracking_error_mc_10_dcee, '- b', ...
     Ts_mpc, Tracking_error_mc_10_mpc, '-- r', ...
     Ts_entropy(1:50), Tracking_error_mc_10_entropy(1:50), '-. g', ...
    'LineWidth', 1.5)
my_legend = legend(' $ \mathcal{D} $, DCEE', ...
                   ' $ \mathcal{D} $, MPC ', ...
                   ' $ \mathcal{D} $, Entropy ');
set(my_legend, 'FontSize', 12, 'Location', 'north');
xlabel('$k$','FontSize', 12);
ylabel('Distance $ \mathcal{D} $ ', 'FontSize', 12);

%% Distance and variance: DCEE vs MPC vs Entropy
figure(6)
subplot(2,1,1)
plot(Ts_dcee, Tracking_error_mc_10_dcee, '- b', ...
     Ts_mpc, Tracking_error_mc_10_mpc, '-- r', ...
     Ts_entropy(1:50), Tracking_error_mc_10_entropy(1:50), '-. g', ...
    'LineWidth', 1.5)
my_legend = legend(' $ \mathcal{D} $, DCEE', ...
                   ' $ \mathcal{D} $, MPC ', ...
                   ' $ \mathcal{D} $, Entropy ');
set(my_legend, 'FontSize', 12, 'Location', 'north', 'Orientation', 'horizontal');
xlabel('$k$','FontSize', 12);
ylabel('Distance $ \mathcal{D} $ ', 'FontSize', 12);

subplot(2,1,2)
plot(Ts_dcee, P_vari_mc_10_dcee, '- b', ...
     Ts_mpc, P_vari_mc_10_mpc, '-- r', ...
     Ts_entropy(1:50), P_vari_mc_10_entropy(1:50), '-. g', ...
    'LineWidth', 1.5)
my_legend = legend(' $ \mathcal{P} $, DCEE', ...
                   ' $ \mathcal{P} $, MPC ', ...
                   ' $ \mathcal{P} $, Entropy ');
set(my_legend, 'FontSize', 12, 'Location', 'north', 'Orientation','horizontal');
xlabel('$k$','FontSize', 12);
ylabel('Variance $ \mathcal{P} $ ', 'FontSize', 12);

%% Distance and variance: DCEE vs MPC vs Entropy vs UCB
figure(7)
subplot(2,1,1)
h = plot(Ts_dcee, Tracking_error_mc_10_dcee, '- b', ...
     Ts_mpc, Tracking_error_mc_10_mpc, '-- r', ...
     Ts_entropy(1:50), Tracking_error_mc_10_entropy(1:50), '-. g', ...
     Ts_ucb, Tracking_error_mc_10_ucb, ':', ...
    'LineWidth', 1.5);
set(h(1), 'Color', [0.3 0.6 1]);  % DCEE in lighter blue
set(h(4), 'Color', 'k');          % UCB in black
my_legend = legend(' $ \mathcal{D} $, DCEE', ...
                   ' $ \mathcal{D} $, MPC ', ...
                   ' $ \mathcal{D} $, Entropy ', ...
                   ' $ \mathcal{D} $, UCB ');
set(my_legend, 'FontSize', 12, 'Location', 'north', 'NumColumns', 2);
xlabel('$k$','FontSize', 12);
ylabel('Distance $ \mathcal{D} $ ', 'FontSize', 12);

subplot(2,1,2)
h = plot(Ts_dcee, P_vari_mc_10_dcee, '- b', ...
     Ts_mpc, P_vari_mc_10_mpc, '-- r', ...
     Ts_entropy(1:50), P_vari_mc_10_entropy(1:50), '-. g', ...
     Ts_ucb, P_vari_mc_10_ucb, ':', ...
    'LineWidth', 1.5);
set(h(1), 'Color', [0.3 0.6 1]);  % DCEE in lighter blue
set(h(4), 'Color', 'k');          % UCB in black
my_legend = legend(' $ \mathcal{P} $, DCEE', ...
                   ' $ \mathcal{P} $, MPC ', ...
                   ' $ \mathcal{P} $, Entropy ', ...
                   ' $ \mathcal{P} $, UCB ');
set(my_legend, 'FontSize', 12, 'Location', 'north', 'NumColumns', 2);
xlabel('$k$','FontSize', 12);
ylabel('Variance $ \mathcal{P} $ ', 'FontSize', 12);

saveas(figure(7), 'd_p_compare_dcee_entropy_mpc_ucb_lego_s1_k', 'fig');
